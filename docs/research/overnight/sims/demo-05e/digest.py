"""Turn the JSON captures into captures/DIGEST.md: per scenario and settings label, each turn's input, moves,
what the chatbot is told (cue + the data it must use), evidence written, AI-literacy p/levels after, pending
task/check, server ms and result size; and a branch-vs-w2 diff of everything a viewer could see.
    python digest.py"""
import json
from pathlib import Path

HERE = Path(__file__).parent / "captures"
SHORT = {"ail_ask": "Ask", "ail_verify": "Verify", "ail_how_fabrication": "fab", "ail_how_confidence": "conf",
         "ail_how_cutoff": "cutoff", "ail_how_agreement": "agree"}


def server_ms(t):
    for line in t.get("console") or []:
        if line.startswith(("tutor_turn", "get_my_progress")):
            return line
    return ""


def told_line(s):
    bits = [f"**{s['move']}**" + (f" ({s['part_id']})" if s.get("part_id") else ""), f"cue: \"{s.get('cue')}\""]
    for k in ("skill", "level", "task", "features"):
        if k in s:
            bits.append(f"{k}={json.dumps(s[k])}")
    if "pattern" in s:
        bits.append("pattern: " + s["pattern"].replace("\n", " / "))
    if "trusted_sources" in s:
        bits.append("trusted_sources: " + (", ".join(f"{x['name']} {x['url']}" for x in s["trusted_sources"]) or "none"))
    if "options" in s:
        bits.append("options: " + " | ".join(f"{o['letter']}. {o['text']}" for o in s["options"])
                    + (f" | {s['extra_option']}. (chatbot writes)" if s.get("extra_option") else ""))
    if "misconceptions" in s:
        bits.append("misconceptions: " + "; ".join(f"{m['wrong_idea']} -> {m['correction']}" for m in s["misconceptions"]))
    for k in ("correct", "correct_option", "intuition", "asked", "name", "note"):
        if k in s:
            bits.append(f"{k}: {s[k]}")
    return "; ".join(bits)


def visible(rec):
    """What a viewer could see, for the branch-vs-w2 diff: moves, literacy skill/level/task, options, progress levels."""
    out = []
    for t in rec["turns"]:
        if t["tool"] == "tutor_turn":
            out.append((t["n"], tuple(t["moves"]), tuple((s["move"], s.get("skill"), s.get("level"), s.get("task"))
                                                         for s in t["told"])))
        elif t["tool"] == "get_my_progress":
            a = t["result"]["ai_literacy"]
            out.append((t["n"], "progress", a["ask"]["level"], a["verify"]["level"], a["how_ai_works"]["level"],
                        tuple(a["how_ai_works"]["held"])))
        else:
            out.append((t["n"], "skipped"))
    return out


lines = ["# Plan A rehearsal captures (generated by digest.py)", ""]
recs = {}
for f in sorted(HERE.glob("*__*.json")):
    label, name = f.stem.split("__")
    recs[(name, label)] = json.loads(f.read_text())

for name in dict.fromkeys(n for n, _ in recs):
    for label in ("branch", "w2", "rewrite"):
        rec = recs.get((name, label))
        if not rec:
            continue
        lines += [f"## {name} [{label}]", "", rec["about"], ""]
        for t in rec["turns"]:
            if t["tool"] == "skipped":
                lines.append(f"- **{t['n']} ({t['shot']})** SKIPPED: {t['note']}")
                continue
            if t["tool"] == "get_my_progress":
                a = t["result"]["ai_literacy"]
                lines.append(f"- **{t['n']} (4d) get_my_progress** ai_literacy: Ask {a['ask']['level']}, Verify "
                             f"{a['verify']['level']}, How AI works {a['how_ai_works']['level']}, held {a['how_ai_works']['held']}; "
                             f"features {json.dumps({k: v['recent'] for k, v in a['question_features'].items()})}; "
                             f"{t['result_chars']} chars; `{server_ms(t)}`")
                continue
            sent = t["sent"]
            lab = {k: v for k, v in sent["this_message"].items() if k not in ("question_depth", "engagement")}
            lines.append(f"- **{t['n']} ({t['shot']})** student: \"{sent['message']}\"; labels {json.dumps(lab)}"
                         + (f"; answer {json.dumps(sent['answer'])}" if "answer" in sent else ""))
            for s in t["told"]:
                lines.append(f"    - {told_line(s)}")
            p = t["after"]["p"]
            lines.append(f"    - focus {[f['id'] for f in t['result'].get('focus', [])]}; evidence "
                         f"{[(e['part_id'], e['evidence_type'], e['score']) for e in t['evidence']]}; after: "
                         + ", ".join(f"{SHORT[k]} {v:.2f}" for k, v in p.items()) + f", how rollup {t['after']['how_rollup']:.2f}"
                         + f"; held {t['after']['held_ail']}; pending task {t['after']['pending_literacy']}; "
                         f"pending check {t['after']['pending_how']}; {t['result_chars']} chars; `{server_ms(t)}`")
        lines.append("")
    b, w = recs.get((name, "branch")), recs.get((name, "w2"))
    if b and w:
        vb, vw = visible(b), visible(w)
        diff = [(x, y) for x, y in zip(vb, vw) if x != y]
        lines += [f"**branch vs w2 ({name}):** " + ("no visible difference" if not diff else
                  "; ".join(f"turn {x[0]}: branch {x[1:]} / w2 {y[1:]}" for x, y in diff)), ""]
ms = [t for r in recs.values() for t in r["turns"] if t.get("console")]
vals = sorted(int(server_ms(t).split()[2].rstrip("ms")) for t in ms if server_ms(t))
walls = sorted(t["wall_ms"] for t in ms)
chars = sorted(t["result_chars"] for r in recs.values() for t in r["turns"] if t["tool"] == "tutor_turn")
over = [l for t in ms for l in t["console"] if "OVER BUDGET" in l]
lines += ["## Timing and size over all captures", "",
          f"- server ms (console): n={len(vals)}, median {vals[len(vals)//2]}, max {vals[-1]}",
          f"- wall ms per MCP call (client, localhost, one session): median {walls[len(walls)//2]}, max {walls[-1]}",
          f"- tutor_turn result chars: median {chars[len(chars)//2]}, max {chars[-1]} (budget 2400); OVER BUDGET lines: {len(over)}"]
(HERE / "DIGEST.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines[-4:]))
